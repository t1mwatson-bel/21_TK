# =====================================================================
# ПОЛУЧЕНИЕ КОЭФФИЦИЕНТА
# =====================================================================

def get_player_cf(rank: str) -> float:
    """Коэффициент на ранг у игрока."""
    if rank is None:
        return 5.0
    rank = str(rank).strip().upper()
    return PLAYER_COEFS.get(rank, 5.0)


def get_banker_cf(rank: str) -> float:
    """Коэффициент на ранг у банкира."""
    if rank is None:
        return 5.0
    rank = str(rank).strip().upper()
    return BANKER_COEFS.get(rank, 5.0)


# Совместимость со старым кодом (если где-то вызывается)
def get_dealer_cf(card: str) -> float:
    """Коэффициент на ранг у банкира (старое имя функции)."""
    return get_banker_cf(card)