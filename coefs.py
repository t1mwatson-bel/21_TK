# =====================================================================
# ПОЛУЧЕНИЕ КОЭФФИЦИЕНТА
# =====================================================================

def get_player_cf(rank: str, suit: str = None) -> float:
    """Коэффициент на карту у игрока."""
    if rank is None:
        return 10.0
    rank = str(rank).strip().upper()
    
    # Если масть не передана, берем среднее или дефолт
    if suit is None:
        return 10.0
    
    suit = str(suit).strip()
    return PLAYER_COEFS.get(rank, {}).get(suit, 10.0)


def get_dealer_cf(rank: str, suit: str = None) -> float:
    """Коэффициент на карту у дилера."""
    if rank is None:
        return 11.0
    rank = str(rank).strip().upper()
    
    if suit is None:
        return 11.0
        
    suit = str(suit).strip()
    return DEALER_COEFS.get(rank, {}).get(suit, 11.0)